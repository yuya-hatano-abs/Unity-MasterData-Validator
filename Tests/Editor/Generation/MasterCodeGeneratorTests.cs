using System.Linq;
using MasterDataTool.EditorTools.Generation;
using MasterDataTool.EditorTools.Importing;
using MasterDataTool.Runtime;
using NUnit.Framework;

namespace MasterDataTool.EditorTools.Tests
{
    /// <summary>
    /// <see cref="MasterCodeGenerator"/> のテストです。
    /// </summary>
    public class MasterCodeGeneratorTests
    {
        static MasterSchema CreateSchema(MasterIdKind idKind, params SchemaField[] fields)
        {
            return new MasterSchema(idKind, fields);
        }

        [Test]
        public void Generate_IntRecord_MatchesExpectedSource()
        {
            var schema = CreateSchema(
                MasterIdKind.Int,
                new SchemaField("price", SchemaFieldType.Int, false, "Price", "int"));
            var options = new MasterCodeOptions("Sample", "MyGame.MasterData");

            var result = MasterCodeGenerator.Generate(schema, options);

            Assert.IsTrue(result.Succeeded);
            Assert.AreEqual("SampleRecord.cs", result.Code.RecordFileName);
            Assert.AreEqual("SampleMaster.cs", result.Code.MasterFileName);
            StringAssert.Contains("public sealed class SampleRecord : IntIdMasterRecord", result.Code.RecordSource);
            StringAssert.Contains("[SerializeField] private int price;", result.Code.RecordSource);
            StringAssert.Contains("public int Price => price;", result.Code.RecordSource);
        }

        [Test]
        public void Generate_AllScalarTypes_ArePresent()
        {
            var schema = CreateSchema(
                MasterIdKind.Int,
                new SchemaField("price", SchemaFieldType.Int, false, "Price", "int"),
                new SchemaField("bigCount", SchemaFieldType.Long, false, "BigCount", "long"),
                new SchemaField("ratio", SchemaFieldType.Float, false, "Ratio", "float"),
                new SchemaField("enabled", SchemaFieldType.Bool, false, "Enabled", "bool"),
                new SchemaField("name", SchemaFieldType.String, false, "Name", "string"),
                new SchemaField("tags", SchemaFieldType.String, true, "Tags", "List<string>"));
            var options = new MasterCodeOptions("All", "MyGame.MasterData");

            var result = MasterCodeGenerator.Generate(schema, options);

            Assert.IsTrue(result.Succeeded);
            StringAssert.Contains("List<string> tags = new List<string>();", result.Code.RecordSource);
            StringAssert.Contains("IReadOnlyList<string> Tags => tags;", result.Code.RecordSource);
        }

        [Test]
        public void Generate_ZeroFields_ProducesEmptyClassBody()
        {
            var schema = CreateSchema(MasterIdKind.Int);
            var options = new MasterCodeOptions("Buff", "MyGame.MasterData");

            var result = MasterCodeGenerator.Generate(schema, options);

            Assert.IsTrue(result.Succeeded);
            const string expected =
                "// <auto-generated>\n" +
                "// このファイルは Master Data Tool によって生成されました。\n" +
                "// 再生成すると上書きされるため、直接編集しないでください。\n" +
                "// </auto-generated>\n" +
                "using System;\n" +
                "using System.Collections.Generic;\n" +
                "using MasterDataTool.Runtime;\n" +
                "using UnityEngine;\n" +
                "\n" +
                "namespace MyGame.MasterData\n" +
                "{\n" +
                "    [Serializable]\n" +
                "    public sealed class BuffRecord : IntIdMasterRecord\n" +
                "    {\n" +
                "    }\n" +
                "}\n";
            Assert.AreEqual(expected, result.Code.RecordSource);
        }

        [Test]
        public void Generate_StringId_UsesStringIdBase()
        {
            var schema = CreateSchema(MasterIdKind.String);
            var options = new MasterCodeOptions("Quest", "MyGame.MasterData");

            var result = MasterCodeGenerator.Generate(schema, options);

            StringAssert.Contains("StringIdMasterRecord", result.Code.RecordSource);
        }

        [Test]
        public void Generate_IsDeterministic()
        {
            var schema = CreateSchema(
                MasterIdKind.Int,
                new SchemaField("name", SchemaFieldType.String, false, "Name", "string"));
            var options = new MasterCodeOptions("Item", "MyGame.MasterData");

            var first = MasterCodeGenerator.Generate(schema, options);
            var second = MasterCodeGenerator.Generate(schema, options);

            Assert.AreEqual(first.Code.RecordSource, second.Code.RecordSource);
            Assert.IsFalse(first.Code.RecordSource.Contains("\r"));
        }

        [Test]
        public void Generate_InvalidMasterName_Fails()
        {
            var schema = CreateSchema(MasterIdKind.Int);
            Assert.IsFalse(MasterCodeGenerator.Generate(schema, new MasterCodeOptions("item", "A.B")).Succeeded);
            Assert.IsFalse(MasterCodeGenerator.Generate(schema, new MasterCodeOptions("1Item", "A.B")).Succeeded);
            Assert.IsFalse(MasterCodeGenerator.Generate(schema, new MasterCodeOptions("Item Master", "A.B")).Succeeded);
            Assert.IsFalse(MasterCodeGenerator.Generate(schema, new MasterCodeOptions("class", "A.B")).Succeeded);
            Assert.IsFalse(MasterCodeGenerator.Generate(schema, new MasterCodeOptions(string.Empty, "A.B")).Succeeded);
        }

        [Test]
        public void Generate_InvalidNamespace_Fails()
        {
            var schema = CreateSchema(MasterIdKind.Int);
            Assert.IsFalse(MasterCodeGenerator.Generate(schema, new MasterCodeOptions("Item", string.Empty)).Succeeded);
            Assert.IsFalse(MasterCodeGenerator.Generate(schema, new MasterCodeOptions("Item", "My..Game")).Succeeded);
            Assert.IsFalse(MasterCodeGenerator.Generate(schema, new MasterCodeOptions("Item", "1Game")).Succeeded);
            Assert.IsFalse(MasterCodeGenerator.Generate(schema, new MasterCodeOptions("Item", "My.class")).Succeeded);
        }

        [Test]
        public void GenerateFromJson_IncludesInferenceWarnings()
        {
            const string json = "{\"records\":[{\"id\":1,\"meta\":{\"a\":1},\"name\":\"A\"}]}";
            var result = MasterCodeGenerator.GenerateFromJson(json, new MasterCodeOptions("Item", "MyGame.MasterData"));

            Assert.IsTrue(result.Succeeded);
            Assert.IsTrue(result.Issues.Any(i => i.Kind == GenerationIssueKind.UnsupportedFieldValue));
        }

        [Test]
        public void GenerateFromJson_InferenceFailure_ReturnsNullCode()
        {
            const string json = "{\"records\":[{\"id\":1},{\"id\":\"A\"}]}";
            var result = MasterCodeGenerator.GenerateFromJson(json, new MasterCodeOptions("Item", "MyGame.MasterData"));

            Assert.IsFalse(result.Succeeded);
            Assert.IsNull(result.Code);
        }

        [Test]
        public void Generate_RecordClassNameCollision_Fails()
        {
            var schema = CreateSchema(
                MasterIdKind.Int,
                new SchemaField("itemRecord", SchemaFieldType.String, false, "ItemRecord", "string"));
            var result = MasterCodeGenerator.Generate(schema, new MasterCodeOptions("Item", "MyGame.MasterData"));

            Assert.IsFalse(result.Succeeded);
            Assert.IsTrue(result.Issues.Any(i => i.Kind == GenerationIssueKind.ReservedFieldName));
        }
    }
}
